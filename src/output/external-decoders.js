function collectHeaderFiles(root, relativeDir) {
  const dir = path.join(root, relativeDir);
  if (!fs.existsSync(dir)) {
    throw new Error(`Jayess image runtime requires externals/libwebp/${relativeDir} for WebP decoder headers`);
  }
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".h"))
    .map((entry) => path.join(relativeDir, entry.name));
}

function copyLibwebpArtifacts(targetDirname, root) {
  const libwebpRoot = path.join(root, "externals", "libwebp");
  const copied = [];
  for (const relative of [
    ...libwebpSourceFiles,
    ...collectHeaderFiles(libwebpRoot, "src/webp"),
    ...collectHeaderFiles(libwebpRoot, "src/dec"),
    ...collectHeaderFiles(libwebpRoot, "src/dsp"),
    ...collectHeaderFiles(libwebpRoot, "src/utils")
  ]) {
    copied.push(copyRequiredFile(
      targetDirname,
      path.join(libwebpRoot, relative),
      path.join("native", "libwebp", relative),
      `Jayess image runtime requires externals/libwebp/${relative} for WebP decoding`
    ));
  }
  copied.push(copyRequiredFile(
    targetDirname,
    path.join(libwebpRoot, "COPYING"),
    path.join("licenses", "libwebp", "COPYING"),
    "Jayess image runtime requires externals/libwebp/COPYING to package WebP decoder license notices"
  ));
  copied.push(copyRequiredFile(
    targetDirname,
    path.join(libwebpRoot, "PATENTS"),
    path.join("licenses", "libwebp", "PATENTS"),
    "Jayess image runtime requires externals/libwebp/PATENTS to package WebP decoder patent notices"
  ));
  copied.push(copyRequiredFile(
    targetDirname,
    path.join(libwebpRoot, "AUTHORS"),
    path.join("licenses", "libwebp", "AUTHORS"),
    "Jayess image runtime requires externals/libwebp/AUTHORS to package WebP decoder attribution notices"
  ));
  const configPath = path.join(targetDirname, "native", "libwebp", "src", "webp", "config.h");
  fs.mkdirSync(path.dirname(configPath), { recursive: true });
  fs.writeFileSync(configPath, `#pragma once

/* Generated by Jayess for the portable libwebp decoder slice. */
#define WEBP_NEAR_LOSSLESS 1
`, "utf8");
  copied.push(configPath);
  return copied;
}

export function copyExternalDecoderArtifacts(targetDirname, runtimeFragmentKeys) {
  if (!runtimeFragmentKeys.includes("image")) {
    return [];
  }
  const root = repositoryRoot();
  const stbRoot = path.join(root, "externals", "stb");
  const stbHeader = path.join(stbRoot, "stb_image.h");
  const stbLicense = path.join(stbRoot, "LICENSE");
  if (!fs.existsSync(stbHeader)) {
    throw new Error("Jayess image runtime requires externals/stb/stb_image.h for PNG/JPEG/BMP/PSD/GIF decoding");
  }
  if (!fs.existsSync(stbLicense)) {
    throw new Error("Jayess image runtime requires externals/stb/LICENSE to package decoder license notices");
  }
  return [
    copyFile(targetDirname, stbHeader, path.join("native", "stb_image.h")),
    copyFile(targetDirname, stbLicense, path.join("licenses", "stb", "LICENSE")),
    ...copyLibwebpArtifacts(targetDirname, root)
  ];
}
